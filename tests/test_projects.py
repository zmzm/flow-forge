def mutate_worker(path, key, ready):
    ready.wait()
    storage.update_task(Path(path), 'one', {key: True})


class ProjectCase(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='flowforge-project-test-')
        self.addCleanup(self.temp.cleanup)
        self.base = Path(self.temp.name)
        self.root = self.base / 'config'
        self.state = self.base / 'state'
        self.env = mock.patch.dict(os.environ, {
            'FLOWFORGE_CONFIG_DIR': str(self.root), 'FLOWFORGE_STATE_DIR': str(self.state),
            'PROJECT_DIR': '/stale/workspace', 'TASKS_FILE': '/stale/queue', 'MATRIX_ENABLED': 'false',
        })
        self.env.start()
        self.addCleanup(self.env.stop)
        self.workspace = self.base / 'external'
        self.workspace.mkdir()
        self.inbox = self.base / 'inbox'
        self.inbox.mkdir()
        self.binary = self.base / 'fake-opencode'
        self.binary.write_text(FAKE)
        self.binary.chmod(0o755)
        self.source = self.base / 'mentori' / 'agents'
        self.source.mkdir(parents=True)
        self.names = ['concept-plan', 'grounded-hard', 'execution-plan', 'review', 'repair', 'custom']
        for name in self.names:
            (self.source / (name + '.md')).write_text(
                '---\ndescription: Fixture ' + name + '\nmode: primary\nmodel: fixture/' + name +
                '\ntemperature: 0.2\nreasoningEffort: high\npermission:\n  edit: allow\n  bash: deny\n---\nFIXTURE_PROMPT_' + name + '\n')
        self.library = self.root / 'library'
        agents.import_library(self.source, self.library, apply=True)
        self.register('one', self.workspace, self.inbox)
        self.context = config.resolve_context('one')

    def register(self, name, workspace, inbox=None, **extra):
        config.add_project(name, {'workspace': workspace, **({'tasks_dir': inbox} if inbox else {}), 'opencode_bin': str(self.binary), **extra})

    def task(self, key='a', text='# A task'):
        path = self.inbox / key / 'task.md'
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        return path

    def workflow(self, name, count=1, agent='review'):
        steps = [{'id': 's' + str(i), 'label': 'Step ' + str(i), 'agent': agent} for i in range(count)]
        storage.atomic_json(self.root / 'workflows' / (name + '.json'), {'steps': steps})
        return steps

    def invoke(self, *args, expected=0):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            code = cli.main([*args, '--json'])
        self.assertEqual(code, expected, out.getvalue())
        result = json.loads(out.getvalue())
        self.assertEqual(result['schema_version'], 1)
        return result



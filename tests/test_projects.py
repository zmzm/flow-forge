class LockTests(ProjectCase):
    def test_workspace_alias_and_shared_queue_conflict_but_distinct_projects_do_not(self):
        lock = storage.acquire_execution(self.context)
        self.addCleanup(lock.close)
        alias = self.base / 'workspace-alias'
        alias.symlink_to(self.workspace)
        shared_workspace = replace(self.context, project_id='alias', workspace=alias, tasks_file=self.base / 'other.jsonl', runs_dir=self.base / 'other-runs')
        self.assertIsNone(storage.acquire_execution(shared_workspace))
        other_workspace = self.base / 'other-workspace'; other_workspace.mkdir()
        shared_queue = replace(self.context, workspace=other_workspace, runs_dir=self.base / 'other-runs')
        self.assertIsNone(storage.acquire_execution(shared_queue))
        distinct = replace(shared_queue, tasks_file=self.base / 'other.jsonl')
        other = storage.acquire_execution(distinct)
        self.assertIsNotNone(other)
        other.close()

    def test_legacy_run_lock_is_also_observed(self):
        handle = pr.acquire_lock(self.context.runs_dir / '.flowforge.lock')
        try:
            self.assertIsNone(storage.acquire_execution(self.context))
        finally:
            pr.release_lock(handle)

    def test_queue_transactions_preserve_concurrent_field_edits(self):
        pr.write_tasks_jsonl(self.context.tasks_file, [{'id': 'one', 'task_file': 'unused', 'status': 'todo'}])
        ctx = multiprocessing.get_context('spawn')
        ready = ctx.Event()
        workers = [ctx.Process(target=mutate_worker, args=(str(self.context.tasks_file), 'field' + str(i), ready)) for i in range(6)]
        for worker in workers: worker.start()
        ready.set()
        for worker in workers:
            worker.join(5)
            self.assertEqual(worker.exitcode, 0)
        task = pr.read_tasks_jsonl(self.context.tasks_file)[0]
        self.assertTrue(all(task['field' + str(i)] for i in range(6)))

    def test_busy_json_is_distinct_and_does_not_recover_active_task(self):
        self.task(); discovery.sync(self.context)
        task_id = pr.read_tasks_jsonl(self.context.tasks_file)[0]['id']
        storage.update_task(self.context.tasks_file, task_id, {'status': 'running'})
        lock = storage.acquire_execution(self.context)
        try:
            result = self.invoke('run', '--project', 'one')
            self.assertEqual(result['reason'], 'busy')
            self.assertTrue(result['busy'])
            self.assertEqual(pr.read_tasks_jsonl(self.context.tasks_file)[0]['status'], 'running')
        finally:
            lock.close()


class EndToEndTests(ProjectCase):
    def test_two_external_projects_run_with_shared_library_and_absolute_outputs(self):
        self.task('a'); self.task('b')
        second_workspace = self.base / 'second'; second_workspace.mkdir()
        second_inbox = self.base / 'second-inbox'; (second_inbox / 'task-1').mkdir(parents=True)
        second_source = second_inbox / 'task-1/task.md'; second_source.write_text('# second')
        self.register('two', second_workspace, second_inbox)
        for name in ('one', 'two'):
            result = self.invoke('run', '--project', name, '--sync', '--max-tasks', '3')
            self.assertEqual(result['failed'], 0)
            self.assertGreater(result['completed'], 0)
            self.assertEqual(result['reason'], 'queue_empty')
            context = config.resolve_context(name)
            for task in pr.read_tasks_jsonl(context.tasks_file):
                self.assertEqual(task['status'], 'done')
                self.assertEqual(len(task['outputs']), 3)
                for value in task['outputs'].values():
                    self.assertTrue(Path(value).is_relative_to(context.artifacts_dir))
                    self.assertTrue(Path(value).exists())
        self.assertEqual(sorted(p.name for p in (self.inbox / 'a').iterdir()), ['task.md'])
        self.assertEqual(sorted(p.name for p in second_source.parent.iterdir()), ['task.md'])
        calls = [json.loads(line) for line in (self.workspace / 'calls.jsonl').read_text().splitlines()]
        self.assertEqual(len(calls), 6)
        self.assertEqual([c['args'][c['args'].index('--agent') + 1] for c in calls[:3]], self.names[:3])
        self.assertEqual(calls[0]['args'][calls[0]['args'].index('--model') + 1], 'zai-coding-plan/glm-5.3-flash')

"""Disposable project, central library and local OpenCode process fixture."""

import contextlib
import io
import json
import os
import tempfile
import unittest
from pathlib import Path
from unittest import mock

import flowforge_agents as agents
import flowforge_cli as cli
import flowforge_config as config
import flowforge_storage as storage

ROOT = Path(__file__).resolve().parents[2]

FAKE = r"""#!/usr/bin/env python3
import json, os, re, sys
from pathlib import Path
args = sys.argv[1:]
workspace = Path(args[args.index('--dir') + 1])
assert Path.cwd() == workspace == Path(os.environ['PWD'])
agent = args[args.index('--agent') + 1]
library = Path(os.environ['OPENCODE_CONFIG_DIR'])
definition = (library / 'agents' / (agent + '.md')).read_text()
assert 'permission:' in definition and 'FIXTURE_PROMPT_' + agent in definition
for reference in re.findall(r'\{file:([^}]+)\}', definition):
    assert Path(reference).is_file(), reference
output = re.search(r"absolute path '([^']+)'", args[-1])
if output is None:
    output = re.search(r"ONLY to '([^']+)'", args[-1])
assert output is not None, args[-1]
record = {'args': args, 'cwd': str(Path.cwd()), 'library': str(library), 'definition': definition}
with (workspace / 'calls.jsonl').open('a') as f:
    f.write(json.dumps(record) + '\n')
if (workspace / 'pause').exists():
    print(json.dumps({'type': 'event', 'sessionID': 'ses-live'}), flush=True)
    import time
    time.sleep(2)
if not (workspace / 'fail').exists():
    Path(output.group(1)).write_text('# generated by ' + agent)
if (workspace / 'fail').exists():
    print(json.dumps({'type': 'error', 'error': {'name': 'FixtureError', 'message': 'failed'}}))
else:
    print(json.dumps({'type': 'event', 'sessionID': 'ses-' + agent}))
"""


class ProjectCase(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="flowforge-project-test-")
        self.addCleanup(self.temp.cleanup)
        self.base = Path(self.temp.name)
        self.root = self.base / "config"
        self.state = self.base / "state"
        self.env = mock.patch.dict(
            os.environ,
            {
                "FLOWFORGE_CONFIG_DIR": str(self.root),
                "FLOWFORGE_STATE_DIR": str(self.state),
                "PROJECT_DIR": "/stale/workspace",
                "TASKS_FILE": "/stale/queue",
                "MATRIX_ENABLED": "false",
            },
        )
        self.env.start()
        self.addCleanup(self.env.stop)
        self.workspace = self.base / "external"
        self.workspace.mkdir()
        self.inbox = self.base / "inbox"
        self.inbox.mkdir()
        self.binary = self.base / "fake-opencode"
        self.binary.write_text(FAKE)
        self.binary.chmod(0o755)
        self.source = self.base / "mentori" / "agents"
        self.source.mkdir(parents=True)
        self.names = [
            "concept-plan",
            "grounded-hard",
            "execution-plan",
            "review",
            "repair",
            "custom",
        ]
        for name in self.names:
            (self.source / (name + ".md")).write_text(
                "---\ndescription: Fixture "
                + name
                + "\nmode: primary\nmodel: fixture/"
                + name
                + "\ntemperature: 0.2\nreasoningEffort: high\npermission:\n  edit: allow\n  bash: deny\n---\nFIXTURE_PROMPT_"
                + name
                + "\n"
            )
        self.library = self.root / "library"
        agents.import_library(self.source, self.library, apply=True)
        self.register("one", self.workspace, self.inbox)
        self.context = config.resolve_context("one")

    def register(self, name, workspace, inbox=None, **extra):
        config.add_project(
            name,
            {
                "workspace": workspace,
                **({"tasks_dir": inbox} if inbox else {}),
                "opencode_bin": str(self.binary),
                **extra,
            },
        )

    def task(self, key="a", text="# A task"):
        path = self.inbox / key / "task.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        return path

    def workflow(self, name, count=1, agent="review"):
        steps = [
            {"id": "s" + str(i), "label": "Step " + str(i), "agent": agent} for i in range(count)
        ]
        storage.atomic_json(self.root / "workflows" / (name + ".json"), {"steps": steps})
        return steps

    def invoke(self, *args, expected=0):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            code = cli.main([*args, "--json"])
        self.assertEqual(code, expected, out.getvalue())
        result = json.loads(out.getvalue())
        self.assertEqual(result["schema_version"], 1)
        return result
